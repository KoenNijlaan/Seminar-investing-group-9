"""
Format market frictions analysis output into publication-ready tables.

Reads pre-computed summaries from data_final/market_frictions/ (generated by
Scripts/06_analysis/05_market_frictions.py) and writes formatted CSV/TeX tables
to data_final/results/tables/.

Output tables:
  table_frictions_interaction.csv / .tex
  table_frictions_signal_on_friction.csv / .tex
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from results_utils import DATA_FINAL, ensure_output_dirs, write_csv_and_tex, stars_from_t

FRICTIONS_DIR = DATA_FINAL / "market_frictions"

SIGNAL_ORDER = [
    "rsj_weekly",
    "rsj_idio",
    "rsj_sys",
    "rsj_idio_weekly",
    "rsj_sys_weekly",
    "res_weekly",
    "res_idio_p025",
    "res_sys_p025",
]

IDIO_ORDER = [
    "rsj_idio",
    "rsj_idio_weekly",
    "res_idio_p025",
]


def fmt_bps(val: float, tstat: float) -> str:
    """Format a bps value (already scaled ×10,000) to 2 decimal places."""
    if pd.isna(val):
        return ""
    return f"{val:.2f}{stars_from_t(tstat)}"


def fmt_coef(val: float, tstat: float, decimals: int = 4) -> str:
    """Format a raw coefficient (not bps) to `decimals` decimal places."""
    if pd.isna(val):
        return ""
    fmt = f"{{:.{decimals}f}}"
    return fmt.format(val) + stars_from_t(tstat)


def fmt_t(tstat: float) -> str:
    if pd.isna(tstat):
        return ""
    return f"({tstat:.2f})"


def main() -> None:
    ensure_output_dirs()

    # -------------------------------------------------------
    # Table 1: Interaction FM regressions
    # -------------------------------------------------------
    inter_path = FRICTIONS_DIR / "friction_interaction_summary.csv"
    if not inter_path.exists():
        raise FileNotFoundError(
            f"Missing: {inter_path}\n"
            "Run Scripts/06_analysis/05_market_frictions.py first."
        )

    inter = pd.read_csv(inter_path)

    # Sort by predefined signal order
    order_map = {s: i for i, s in enumerate(SIGNAL_ORDER)}
    inter["_order"] = inter["signal"].map(order_map).fillna(99)
    inter = inter.sort_values("_order").drop(columns=["_order"]).reset_index(drop=True)

    rows_inter = []
    for _, r in inter.iterrows():
        rows_inter.append({
            "Signal":           r["label"],
            "N_weeks":          int(r["n_weeks"]) if pd.notna(r["n_weeks"]) else "",
            "beta_Z_bps":       fmt_bps(r["mean_z_bps"],     r["t_z"]),
            "t_Z":              fmt_t(r["t_z"]),
            "beta_illiq_bps":   fmt_bps(r["mean_illiq_bps"], r["t_illiq"]),
            "t_illiq":          fmt_t(r["t_illiq"]),
            "beta_inter_bps":   fmt_bps(r["mean_inter_bps"], r["t_inter"]),
            "t_inter":          fmt_t(r["t_inter"]),
        })

    df_inter_out = pd.DataFrame(rows_inter)
    write_csv_and_tex(df_inter_out, "table_frictions_interaction")
    print("Saved: table_frictions_interaction.csv / .tex")

    # -------------------------------------------------------
    # Table 2: Signal-on-Friction regressions
    # -------------------------------------------------------
    sof_path = FRICTIONS_DIR / "signal_on_friction_summary.csv"
    if not sof_path.exists():
        raise FileNotFoundError(
            f"Missing: {sof_path}\n"
            "Run Scripts/06_analysis/05_market_frictions.py first."
        )

    sof = pd.read_csv(sof_path)

    idio_order_map = {s: i for i, s in enumerate(IDIO_ORDER)}
    sof["_order"] = sof["signal"].map(idio_order_map).fillna(99)
    sof = sof.sort_values("_order").drop(columns=["_order"]).reset_index(drop=True)

    rows_sof = []
    for _, r in sof.iterrows():
        rows_sof.append({
            "Signal":            r["label"],
            "N_weeks":           int(r["n_weeks"]) if pd.notna(r["n_weeks"]) else "",
            "delta_univ":        fmt_coef(r["mean_delta_univ"], r["t_delta_univ"], decimals=4),
            "t_univ":            fmt_t(r["t_delta_univ"]),
            "delta_ctrl":        fmt_coef(r["mean_delta_ctrl"], r["t_delta_ctrl"], decimals=4),
            "t_ctrl":            fmt_t(r["t_delta_ctrl"]),
        })

    df_sof_out = pd.DataFrame(rows_sof)
    write_csv_and_tex(df_sof_out, "table_frictions_signal_on_friction")
    print("Saved: table_frictions_signal_on_friction.csv / .tex")

    # Print to console
    print("\n--- Interaction FM (bps/week) ---")
    print(df_inter_out.to_string(index=False))

    print("\n--- Signal-on-Friction ---")
    print(df_sof_out.to_string(index=False))


if __name__ == "__main__":
    main()
